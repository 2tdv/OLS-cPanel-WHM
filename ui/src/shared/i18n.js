/** Catalog text for an API error, with its code and the server's own message for support. */
export function errorMessage(error) {
  if (!error) return ''
  const { t, te } = i18n.global
  const text = te(`errors.${error.code}`) ? t(`errors.${error.code}`) : t('errors.generic')
  return error.message && error.message !== error.code
    ? t('errors.withCode', { text, code: error.code, detail: error.message })
    : text
}
