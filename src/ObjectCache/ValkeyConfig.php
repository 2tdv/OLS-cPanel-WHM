<?php
declare(strict_types=1);

namespace OlsCpanel\ObjectCache;

/**
 * Names, limits and the generated text of the per-account object cache (FV-09, docs/product-interfaces.md,
 * "Object cache"). The engine binary is one constant: Valkey from AlmaLinux 9 AppStream (valkey 8.0.x,
 * /usr/bin/valkey-server); where only Redis is available (AlmaLinux 8, or 9 without the package) change
 * SERVER and CLI to /usr/bin/redis-server and /usr/bin/redis-cli, in the unit template too. The commands used
 * (rename-command, unixsocket, maxmemory) are common to Valkey 7/8 and Redis 6/7.
 */
final class ValkeyConfig
{
    public const SERVER = '/usr/bin/valkey-server';
    public const CLI = '/usr/bin/valkey-cli';
    public const UNIT_PREFIX = 'ols-cpanel-objcache@';
    /** The account's socket directory below its home (owner the account, mode 0700). */
    public const SOCKET_DIR = '.ols-objcache';
    public const SOCKET_NAME = 'valkey.sock';
    public const MIN_MEMORY_MB = 16;
    public const MAX_MEMORY_MB = 8192;
    public const DEFAULT_MEMORY_MB = 64;
    /** Unix socket paths are limited to 107 bytes (sun_path); stay below. */
    public const MAX_SOCKET_PATH = 100;
    /** Account names as the compiler accepts them (CachePolicy::USER), at most 32 characters. */
    public const USER = '/^[a-z0-9][a-z0-9_.-]{0,31}$/D';
    /** Commands an account must not reach: they would lift the memory limit, load code, replicate or write files. */
    public const DISABLED_COMMANDS = ['CONFIG', 'DEBUG', 'MODULE', 'REPLICAOF', 'SLAVEOF', 'FAILOVER', 'SAVE', 'BGSAVE',
        'BGREWRITEAOF', 'SYNC', 'PSYNC'];

    public static function validUser(string $user): bool
    {
        return preg_match(self::USER, $user) === 1 && !str_contains($user, '..') && $user !== 'root';
    }

    /** "64" to 64; null when it is not a plain integer inside the limits (no sign, no leading zero, no unit). */
    public static function parseMemory(string $text): ?int
    {
        if (!preg_match('/^[1-9][0-9]{0,4}$/D', $text)) {
            return null;
        }
        $mb = (int) $text;
        return $mb >= self::MIN_MEMORY_MB && $mb <= self::MAX_MEMORY_MB ? $mb : null;
    }

    public static function unit(string $user): string
    {
        return self::UNIT_PREFIX . $user . '.service';
    }

    public static function socketDir(string $home): string
    {
        return $home . '/' . self::SOCKET_DIR;
    }

    public static function socket(string $home): string
    {
        return self::socketDir($home) . '/' . self::SOCKET_NAME;
    }

    /** MemoryMax in MB for a maxmemory: a quarter above plus 32 MB for the process, buffers and fragmentation. */
    public static function memoryMax(int $memoryMb): int
    {
        return (int) ceil($memoryMb * 1.25) + 32;
    }

    /** The configuration file text (byte-exact contract; tests/objcache.php). */
    public static function render(string $user, string $home, int $memoryMb): string
    {
        $dir = self::socketDir($home);
        $lines = [
            "# OLS-cPanel object cache for $user. Generated by ols-cpanel; changes are overwritten.",
            'port 0',
            'unixsocket ' . self::socket($home),
            'unixsocketperm 600',
            'protected-mode yes',
            'daemonize no',
            'dir ' . $dir,
            'logfile ""',
            'loglevel notice',
            'databases 16',
            'maxclients 256',
            'timeout 300',
            "maxmemory {$memoryMb}mb",
            'maxmemory-policy allkeys-lru',
            'save ""',
            'appendonly no',
            'stop-writes-on-bgsave-error no',
            'enable-debug-command no',
            'enable-module-command no',
            'enable-protected-configs no',
        ];
        foreach (self::DISABLED_COMMANDS as $command) {
            $lines[] = "rename-command $command \"\"";
        }
        return implode("\n", $lines) . "\n";
    }

    /** The per-account systemd drop-in (text contract; tests/objcache.php). */
    public static function dropIn(string $home, int $memoryMb): string
    {
        return "# OLS-cPanel object cache: per-account settings. Generated by ols-cpanel; changes are overwritten.\n"
            . "[Service]\nReadWritePaths=" . self::socketDir($home) . "\nMemoryMax=" . self::memoryMax($memoryMb) . "M\n";
    }
}
