def low(text):
    """ASCII-only lower case (like PHP's strtolower): other characters never compare equal to a keyword."""
    return text.translate(_LOWER)

def words(text):
    """Blank-separated words (spaces and tabs only)."""
    return [w for w in re.split(r"[ \t]+", text) if w != ""]

class Blocked(ValueError):
    """ModSecurity state that OLS cannot reproduce; compilation keeps the current state."""

def logical_lines(text):
    """(line number, text) of every directive line: backslash continuations joined (the backslash removed, the
    next line appended as is), blank and comment lines dropped. A comment ending in a backslash continues into the
    next line under Apache and not under libmodsecurity 3; both agree while that next line is a comment or blank (the
    commented examples of the OWASP Core Rule Set's crs-setup.conf), so only a comment continued into a directive is
    ambiguous, returned as None at the comment's line (the directive is not used)."""
    out, pending, start, comment = [], None, 0, None
    for number, raw in enumerate(text.split("\n"), 1):
        line = raw[:-1] if raw.endswith("\r") else raw
        if comment is not None:
            stripped = line.lstrip(" \t")
            if stripped.startswith("#") and line.endswith("\\"):
                continue
            if not stripped.strip(" \t") or stripped.startswith("#"):
                comment = None
                continue
            out.append((comment, None))
            comment = None
            continue
        if pending is None:
            start = number
            stripped = line.lstrip(" \t")
            if stripped.startswith("#"):
                if line.endswith("\\"):
                    comment = number
                continue
            pending = ""
        if line.endswith("\\"):
            pending += line[:-1]
            continue
        pending += line
        if pending.strip(" \t"):
            out.append((start, pending.strip(" \t")))
        pending = None
    if pending is not None and pending.strip(" \t"):
        out.append((start, pending.strip(" \t")))
    return out

def split_args(line):
    """Apache-style arguments: blank-separated, double- or single-quoted (a backslash escapes the quote
    character inside quotes). Returns None for an unterminated quote."""
    args, i, n = [], 0, len(line)
    while i < n:
        if line[i] in " \t":
            i += 1
            continue
        if line[i] in "\"'":
            quote, i, value = line[i], i + 1, ""
            while i < n and line[i] != quote:
                if line[i] == "\\" and i + 1 < n and line[i + 1] == quote:
                    value += quote
                    i += 2
                    continue
                value += line[i]
                i += 1
            if i >= n:
                return None
            args.append(value)
            i += 1
            continue
        start = i
        while i < n and line[i] not in " \t":
            i += 1
        args.append(line[start:i])
    return args

def split_actions(text):
    """Action list items: comma-separated outside single quotes, each trimmed. None when a quote is open."""
    items, current, quoted = [], "", False
    for char in text:
        if char == "'":
            quoted = not quoted
        if char == "," and not quoted:
            items.append(current.strip(" \t"))
            current = ""
            continue
        current += char
    if quoted:
        return None
    items.append(current.strip(" \t"))
    return [i for i in items if i != ""]

def _unquote(value):
    return value[1:-1] if len(value) >= 2 and value[0] == "'" and value[-1] == "'" else value

def split_variables(text):
    """Variable names of a SecRule target list, or None when it cannot be read: `!`/`&` prefixes, `NAME`,
    `NAME:key`, `NAME:/regex/` (which may contain `|`) and `NAME:'key'`, separated by `|`."""
    names, i, n = [], 0, len(text)
    while i < n:
        while i < n and text[i] in "!&":
            i += 1
        start = i
        while i < n and NAME_CHAR.match(text[i]):
            i += 1
        if i == start:
            return None
        names.append(text[start:i].lower())
        if i < n and text[i] == ":":
            i += 1
            if names[-1] == "xml":  # an XPath expression, not a regular expression
                while i < n and text[i] != "|":
                    i += 1
            elif i < n and text[i] == "/":
                i += 1
                while i < n and text[i] != "/":
                    i += 2 if text[i] == "\\" else 1
                if i >= n:
                    return None
                i += 1
            elif i < n and text[i] == "'":
                i += 1
                while i < n and text[i] != "'":
                    i += 1
                if i >= n:
                    return None
                i += 1
            else:
                while i < n and text[i] != "|":
                    i += 1
        if i < n:
            if text[i] != "|":
                return None
            i += 1
            if i == n:
                return None
    return names

class RuleChecker:
    """Reads the loaded files in order and records what libmodsecurity 3 would do differently."""

    def __init__(self):
        self.blockers, self.differences, self.data_files = [], [], []
        self.ids, self.rules, self.defaults, self.modifiers = {}, [], [], []
        self.body_access, self.response_access = False, False
        self.pending_chain = False
        self.engine = None

    def block(self, where, reason):
        self.blockers.append(f"{where}: {reason}")

    def differ(self, code, where, detail, weaker=False):
        entry = {"code": code, "where": where, "detail": detail, "weaker": weaker}
        if entry not in self.differences:
            self.differences.append(entry)

    def check_file(self, path, text, data_base=None):
        """`data_base`: directory relative data files are resolved against (the file's own directory)."""
        for number, line in logical_lines(text):
            where = f"{path}:{number}"
            if line is None:
                self.block(where, "comment line ends with a line continuation")
                continue
            self.directive(where, line, data_base, in_file=True)
        if self.pending_chain:
            self.block(path, "the last rule announces a chain that never follows")
            self.pending_chain = False

    def directive(self, where, line, data_base=None, in_file=False):
        if line.startswith("<"):
            self.block(where, "Apache configuration sections are not translated")
            return
        args = split_args(line)
        if not args:
            self.block(where, "unterminated quote")
            return
        name, rest = low(args[0]), args[1:]
        if name in REFUSED:
            self.block(where, f"{args[0]} is refused by libmodsecurity 3")
        elif name in NOT_QUALIFIED:
            self.block(where, f"{args[0]} is not qualified: {NOT_QUALIFIED[name]}")
        elif name in OFF_ONLY:
            if [low(a) for a in rest] != ["off"]:
                self.block(where, f"{args[0]} is supported by libmodsecurity 3 only with Off")
        elif name in IGNORED:
            self.differ("ignored-" + name, where, f"{args[0]} is ignored by libmodsecurity 3: {IGNORED[name]}")
        elif name in PRODUCT_AUDIT:
            if in_file:
                self.differ("product-audit-log", where, f"{args[0]} is replaced by the product audit log settings")
        elif name not in PASS:
            self.block(where, f"unknown directive {args[0]}")
        else:
            self.known(where, name, args[0], rest, data_base)

    def known(self, where, name, spelled, rest, data_base):
        if name in VALUES and (len(rest) != 1 or low(rest[0]) not in VALUES[name]):
            self.block(where, f"{spelled} has an unsupported value")
            return
        if name == "secargumentseparator" and (len(rest) != 1 or len(rest[0]) != 1):
            self.block(where, "SecArgumentSeparator must be a single character")
            return
        if name == "secrequestbodyaccess" and low(rest[0]) == "on":
            self.body_access = True
        if name == "secresponsebodyaccess" and low(rest[0]) == "on":
            self.response_access = True
        if name == "secrule":
            if len(rest) not in (2, 3):
                self.block(where, "SecRule needs targets, an operator and optional actions")
                return
            if split_variables(rest[0]) is None or not all(v in VARIABLES for v in split_variables(rest[0])):
                self.block(where, "unknown or unreadable SecRule targets")
                return
            self.operator(where, rest[1], data_base)
            self.rule(where, rest[2] if len(rest) == 3 else "")
        elif name == "secaction":
            if len(rest) != 1:
                self.block(where, "SecAction needs one action list")
                return
            self.rule(where, rest[0])
        elif name == "secdefaultaction":
            if len(rest) != 1:
                self.block(where, "SecDefaultAction needs one action list")
                return
            self.default_action(where, rest[0])
        elif name == "secmarker":
            if len(rest) != 1:
                self.block(where, "SecMarker needs one name")
        elif name == "secruleremovebyid":
            self.by_ids(where, words(" ".join(rest)), spelled)
        elif name in ("secruleupdatetargetbyid", "secruleupdateactionbyid"):
            if len(rest) not in (2, 3):
                self.block(where, f"{spelled} needs a rule id and its update")
                return
            self.by_ids(where, [rest[0]], spelled)
            if name == "secruleupdateactionbyid":
                self.actions(where, rest[1])
            else:
                for targets in rest[1:]:
                    if split_variables(targets) is None or not all(v in VARIABLES for v in split_variables(targets)):
                        self.block(where, "unknown or unreadable update targets")
        elif name in ("secruleremovebytag", "secruleupdatetargetbytag"):
            if not rest:
                self.block(where, f"{spelled} needs a tag")
                return
            if REGEX_META.search(rest[0]):
                self.block(where, "ModSecurity 2 matches tags by regular expression, libmodsecurity 3 exactly")
                return
            self.modifiers.append(("tag", rest[0], len(self.rules), where))

    def operator(self, where, text, data_base):
        body = text[1:] if text.startswith("!") else text
        if not body.startswith("@"):
            return  # an implicit @rx
        match = re.match(r"@([A-Za-z0-9]+)(?:[ \t]+(.*))?\Z", body, re.S)
        if not match:
            self.block(where, "unreadable operator")
            return
        name, argument = match.group(1).lower(), match.group(2) or ""
        if name == "geolookup":
            # SecGeoLookupDb is refused, so no geolocation database exists: the lookup fails and the operator never
            # matches, under Apache and under libmodsecurity 3 alike (the OWASP Core Rule Set's rule 910100).
            self.differ("geolookup-without-database", where, "@geoLookup never matches: no geolocation database is configured")
        elif name in OPERATORS_NOT_QUALIFIED:
            self.block(where, f"operator @{match.group(1)} is not qualified for libmodsecurity 3 in the product")
        elif name not in OPERATORS:
            self.block(where, f"unknown operator @{match.group(1)}")
        elif name in FILE_OPERATORS:
            for item in words(argument):
                if re.match(r"^[a-z][a-z0-9+.-]*://", item, re.I):
                    self.block(where, "rule data from a URL is not qualified")
                    continue
                path = item if item.startswith("/") else (data_base + "/" + item if data_base else "")
                if not VENDOR_DATA.match(path):
                    self.block(where, f"rule data file {item} is outside the vendor configurations")
                elif path not in self.data_files:
                    self.data_files.append(path)

    def actions(self, where, text):
        """Checks an action list; returns its items or None."""
        items = split_actions(text)
        if items is None:
            self.block(where, "unterminated quote in the action list")
            return None
        for item in items:
            key, _, value = item.partition(":")
            key = low(key.strip(" \t"))
            if key in ACTIONS_REFUSED:
                self.block(where, f"action {key} is refused by libmodsecurity 3")
            elif key not in ACTIONS:
                self.block(where, f"unknown action {key}")
            elif key == "t" and low(value.strip(" \t")) not in TRANSFORMATIONS:
                self.block(where, "unknown transformation")
            elif key == "ctl":
                option, _, setting = value.partition("=")
                if low(option.strip(" \t")) not in CTL:
                    self.block(where, "ctl option is not supported by libmodsecurity 3")
                elif low(option.strip(" \t")) == "requestbodyprocessor" and low(setting.strip(" \t")) not in BODY_PROCESSORS:
                    self.block(where, "request body processor is not supported by libmodsecurity 3")
            elif key in COLLECTION_ACTIONS:
                self.differ("persistent-collections", where,
                            "collections live in each OLS process's memory (SecDataDir is not used by libmodsecurity 3)")
        return items

    def rule(self, where, text):
        items = self.actions(where, text) if text else []
        if items is None:
            return
        keys = [low(i.partition(":")[0].strip(" \t")) for i in items]
        values = {k: i.partition(":")[2].strip(" \t") for k, i in zip(keys, items)}
        child, self.pending_chain = self.pending_chain, "chain" in keys
        if child:
            if "id" in keys:
                self.block(where, "a chained rule carries its own id")
            return
        if "id" not in keys or not RULE_ID.match(_unquote(values["id"])):
            self.block(where, "rule without a numeric id")
            return
        rule_id = int(_unquote(values["id"]))
        if rule_id in self.ids:
            self.block(where, f"rule id {rule_id} is already defined at {self.ids[rule_id]}")
            return
        phase = PHASES.get(low(_unquote(values.get("phase", "2"))))
        if phase is None:
            self.block(where, "unknown phase")
            return
        self.ids[rule_id] = where
        tags = [_unquote(i.partition(":")[2].strip(" \t")) for k, i in zip(keys, items) if k == "tag"]
        self.rules.append({"id": rule_id, "phase": phase, "tags": tags})

    def default_action(self, where, text, inline=False):
        items = self.actions(where, text)
        if items is None:
            return
        keys = [low(i.partition(":")[0].strip(" \t")) for i in items]
        bad = [k for k in keys if k not in DEFAULT_ACTION_OK]
        if bad or "t:none" in [low(i.replace(" ", "")) for i in items]:
            self.block(where, "SecDefaultAction holds actions libmodsecurity 3 refuses there")
            return
        if not any(k in DISRUPTIVE for k in keys) or "phase" not in keys:
            self.block(where, "SecDefaultAction needs a phase and a disruptive action")
            return
        phase = PHASES.get(low(_unquote(items[keys.index("phase")].partition(":")[2].strip(" \t"))))
        if phase is None:
            self.block(where, "unknown phase")
            return
        norm = ",".join(sorted(low(i.replace(" ", "").replace("\t", "")) for k, i in zip(keys, items) if k != "phase"))
        if not inline and any(d["phase"] == phase and d["file"] == where.rsplit(":", 1)[0] for d in self.defaults):
            self.block(where, "SecDefaultAction for one phase twice in one file")
            return
        self.defaults.append({"phase": phase, "norm": norm, "text": text, "where": where, "inline": inline,
                              "file": where.rsplit(":", 1)[0], "after": sum(1 for r in self.rules if r["phase"] == phase),
                              "emit": True})

    def by_ids(self, where, tokens, spelled):
        if not tokens:
            self.block(where, f"{spelled} needs rule ids")
        for token in tokens:
            match = ID_RANGE.match(_unquote(token))
            if not match:
                self.block(where, f"{spelled} has an unreadable rule id")
                continue
            low = int(match.group(1))
            high = int(match.group(3)) if match.group(3) else low
            if high < low:
                self.block(where, f"{spelled} has an empty id range")
                continue
            self.modifiers.append(("id", (low, high), len(self.rules), where))

    def finish(self):
        """Checks that need the whole load order: modifiers that ModSecurity 2 applies only to rules defined
        before them (libmodsecurity 3 applies them to every rule), and default actions (ModSecurity 2 applies
        each to the rules after it; libmodsecurity 3 accumulates them and applies all to every rule)."""
        for kind, target, defined, where in self.modifiers:
            later = self.rules[defined:]
            if kind == "id":
                hit = [r["id"] for r in later if target[0] <= r["id"] <= target[1]]
            else:
                hit = [r["id"] for r in later if target in r["tags"]]
            if hit:
                self.block(where, f"modifies rule {hit[0]}, which is loaded later (ModSecurity 2 ignores it, libmodsecurity 3 applies it)")
            if kind == "tag" and any(target in t and target != t for r in self.rules for t in r["tags"]):
                self.differ("tag-match", where, "ModSecurity 2 also matches tags that contain the text; libmodsecurity 3 only equal tags")
        for phase in sorted({d["phase"] for d in self.defaults}):
            mine = [d for d in self.defaults if d["phase"] == phase]
            total = sum(1 for r in self.rules if r["phase"] == phase)
            # The built-in default governs the rules before the first SecDefaultAction of the phase.
            active = {BUILTIN_DEFAULT} if mine[0]["after"] > 0 else set()
            for index, entry in enumerate(mine):
                end = mine[index + 1]["after"] if index + 1 < len(mine) else total
                if end > entry["after"]:
                    active.add(entry["norm"])
                elif entry["inline"]:
                    entry["emit"] = False  # superseded before any rule of its phase: ModSecurity 2 never applies it
                    self.differ("superseded-default-action", entry["where"],
                                f"SecDefaultAction for phase {phase} governs no rule and is not loaded")
            emitted = {d["norm"] for d in mine if d["emit"]} or {BUILTIN_DEFAULT}
            if len(emitted) > 1 or not active <= emitted:
                self.block(mine[-1]["where"], f"rules of phase {phase} have different default actions under ModSecurity 2;"
                                              " libmodsecurity 3 applies one set to all of them")
        if self.body_access:
            self.differ("oversized-request-body", "SecRequestBodyAccess",
                        "OLS does not inspect a request body larger than SecRequestBodyLimit (Apache inspects or rejects it)", True)
        if self.response_access:
            self.differ("oversized-response-body", "SecResponseBodyAccess",
                        "OLS does not inspect a response body larger than SecResponseBodyLimit", True)

    def track_engine(self, line):
        """The last SecRuleEngine value (ModSecurity 2's default is Off, libmodsecurity 3 evaluates rules when
        it is not set, so the compiler states it explicitly)."""
        args = split_args(line) or [""]
        if low(args[0]) == "secruleengine" and len(args) == 2 and low(args[1]) in VALUES["secruleengine"]:
            self.engine = {"on": "On", "off": "Off", "detectiononly": "DetectionOnly"}[low(args[1])]

SAFE_VALUE = re.compile(r"^[A-Za-z0-9._/:-]*\Z")
MODSEC2_SECTIONS = {"security2_module": 1, "ruid2_module": 2, "mpm_itk_module": 2}
MODSEC2_DROPPED = {1: {"secauditlog", "secdebuglog", "secdebugloglevel"}, 2: {"secauditlogstoragedir", "secauditlogtype"}}

def _sha256(text):
    return hashlib.sha256(text.encode("utf-8", "surrogateescape")).hexdigest()

def _inline(value):
    if "`" in value or "\n" in value or "\r" in value or value.endswith("\\") \
            or len(value.encode("utf-8", "surrogateescape")) > MAX_INLINE:
        raise Blocked("a ModSecurity directive cannot be passed to OLS as one module parameter")
    return {"key": "modsecurity_rules", "value": "`" + value + "`", "default": None}

def _read(read, name, path):
    record = read(name, ["/usr/bin/cat", path])
    if record["exit_code"] != 0:
        raise Blocked(f"unable to read {path}")
    return record["stdout"]

def translate_cpanel(read):
    """cPanel's ModSecurity state -> {"state": "translated", "entries": [...], "checker": RuleChecker, ...} or
    {"state": "absent"} when Apache has no ModSecurity. Raises Blocked when the state cannot be read."""
    present = [read("modsec-present", ["/usr/bin/test", "-e", path])["exit_code"] == 0 for path in (MODSEC2_CONF, MODULE_CONF)]
    if not any(present):
        return {"state": "absent"}
    if not all(present):
        raise Blocked("ModSecurity is half installed (modsec2.conf and the Apache module must both be present or both absent)")
    checker, entries, inputs, includes, disabled, rule_files = RuleChecker(), [], [], [], [], []

    def fetch(name, path):
        text = _read(read, name, path)
        inputs.append({"path": path, "sha256": _sha256(text)})
        return text

    # EA4's wrapper: only the known directives, inside <IfModule security2_module>.
    stack = []
    for number, line in logical_lines(fetch("modsec-conf", MODSEC2_CONF)):
        where = f"{MODSEC2_CONF}:{number}"
        if line is None:
            checker.block(where, "comment line ends with a line continuation")
            continue
        opened = re.match(r"^<IfModule[ \t]+([A-Za-z0-9_.]+)[ \t]*>\Z", line, re.I)
        if opened:
            if MODSEC2_SECTIONS.get(opened.group(1)) != len(stack) + 1:
                checker.block(where, f"unexpected section {opened.group(1)}")
            stack.append(opened.group(1))
            continue
        if re.match(r"^</IfModule[ \t]*>\Z", line, re.I):
            if not stack:
                checker.block(where, "unbalanced section")
            else:
                stack.pop()
            continue
        args = split_args(line) or [""]
        name = low(args[0])
        if not stack:
            checker.block(where, "directive outside <IfModule security2_module>")
        elif len(stack) > 2:
            checker.block(where, "unexpected section depth")
        elif name in MODSEC2_DROPPED[len(stack)]:
            checker.differ("product-audit-log", where, f"{args[0]} is replaced by the product audit log settings")
        elif len(stack) != 1:
            checker.block(where, f"unexpected directive {args[0]}")
        elif name == "include" and len(args) == 2:
            includes.append(args[1])
        elif name == "secdefaultaction" and len(args) == 2 and '"' not in args[1]:
            before = len(checker.defaults)
            checker.default_action(where, args[1], inline=True)
            if len(checker.defaults) > before:
                entries.append(dict(_inline(f'SecDefaultAction "{args[1]}"'), default=checker.defaults[-1]))
        elif name == "secrequestbodylimitaction" and len(args) == 2 and low(args[1]) in VALUES[name]:
            entries.append(_inline(f"SecRequestBodyLimitAction {args[1]}"))
        else:
            checker.block(where, f"unexpected directive {args[0]}")
    if stack:
        checker.block(MODSEC2_CONF, "unbalanced section")
    if includes != [USER_CONF, CPANEL_CONF]:
        checker.block(MODSEC2_CONF, "must include exactly modsec2.user.conf, then modsec2.cpanel.conf")

    def load(path, text):
        lines = logical_lines(text)
        for _, line in lines:
            if line is not None:
                checker.track_engine(line)
        checker.check_file(path, text, path.rsplit("/", 1)[0])
        if lines:
            rule_files.append(path)
            entries.append({"key": "modsecurity_rules_file", "value": path, "default": None})

    load(USER_CONF, fetch("modsec-user", USER_CONF))
    # WHM's generated file (template modsec2.cpanel.conf.tmpl): settings, includes, disabled rules.
    for number, line in logical_lines(fetch("modsec-cpanel", CPANEL_CONF)):
        where = f"{CPANEL_CONF}:{number}"
        setting = re.match(r'^(Sec[A-Za-z0-9]+) "([^"]*)"\Z', line or "")
        include = re.match(r'^Include "([^"]+)"\Z', line or "")
        removal = re.match(r"^SecRuleRemoveById ([0-9]{1,10})\Z", line or "")
        if setting:
            name, value = setting.group(1), setting.group(2)
            if not SAFE_VALUE.match(value):
                checker.block(where, f"{name} has an unsupported value")
                continue
            blockers = len(checker.blockers)
            checker.directive(where, f"{name} {value}")
            if len(checker.blockers) == blockers and low(name) in PASS | OFF_ONLY:
                checker.track_engine(f"{name} {value}")
                entries.append(_inline(f"{name} {value}"))
        elif include:
            path = include.group(1)
            if not VENDOR_FILE.match(path):
                checker.block(where, f"included file {path} is outside the vendor configurations")
            elif len(rule_files) >= MAX_FILES:
                checker.block(where, "too many rule files for one OLS module block")
            else:
                load(path, fetch("modsec-rules", path))
        elif removal:
            checker.directive(where, line)
            disabled.append(int(removal.group(1)))
            entries.append(_inline(line))
        else:
            checker.block(where, "unexpected line in WHM's generated configuration")
    for path in list(checker.data_files):
        fetch("modsec-data", path)
    checker.finish()
    if checker.engine is None:
        entries.insert(0, _inline("SecRuleEngine Off"))  # ModSecurity 2's default
    for directive in (f"SecAuditLog {AUDIT_LOG}", "SecAuditLogType Serial", f"SecAuditLogParts {AUDIT_PARTS}",
                      "SecAuditLogFileMode 0600"):
        entries.append(_inline(directive))
    return {"state": "translated", "entries": [e for e in entries if e["default"] is None or e["default"]["emit"]],
            "checker": checker, "inputs": inputs, "rule_files": rule_files, "disabled_rules": disabled,
            "engine": checker.engine or "Off"}

def userdata_engine_off(text, name):
    """cPanel's per-domain disable: the userdata key secruleengineoff of the vhost ("1" off; absent, "" or "0" on)."""
    values = []
    for raw in text.split("\n"):
        line = raw[:-1] if raw.endswith("\r") else raw
        if line.startswith("secruleengineoff:"):
            values.append(line[len("secruleengineoff:"):].strip(" \t").strip("'\""))
    if not values:
        return False
    if len(values) > 1 or values[0] not in ("", "0", "1"):
        raise Blocked(f"unreadable secruleengineoff in the userdata of {name}")
    return values[0] == "1"

POLICY_KEYS = {"exceptions", "per_client", "ip_allow", "ip_block", "accept_differences", "evaluated_at"}
PER_CLIENT = (("staticReqPerSec", 0, 1000000), ("dynReqPerSec", 0, 1000000), ("outBandwidth", 0, 2147483647),
              ("inBandwidth", 0, 2147483647), ("softLimit", 1, 1000000), ("hardLimit", 1, 1000000),
              ("gracePeriod", 1, 3600), ("banPeriod", 1, 31536000))
EXCEPTION_KEYS = {"vhost", "rule_ids", "engine", "reason", "approver", "expires"}
MAX_LIST = 1000
PRINTABLE = re.compile(r"^[\x20-\x7e]+\Z")
LIMIT_TIME = 4611686018427387904

def _int(value, minimum, maximum):
    return isinstance(value, int) and not isinstance(value, bool) and minimum <= value <= maximum

def _network(entry, trusted):
    """Normalized IP or network for an OLS access list (a single address without its prefix length)."""
    if not isinstance(entry, str) or not re.match(r"^[0-9A-Fa-f:.]{2,45}(/([0-9]|[1-9][0-9]{1,2}))?\Z", entry) \
            or (":" in entry and "." in entry):
        raise ValueError("invalid address in the security input")
    try:
        network = ipaddress.ip_network(entry, strict=True)
    except ValueError:
        raise ValueError(f"invalid address {entry}") from None
    if network.prefixlen == 0:
        raise ValueError(f"{entry} covers every client")
    loopback = ipaddress.ip_network("127.0.0.0/8") if network.version == 4 else ipaddress.ip_network("::1/128")
    if not trusted and network.overlaps(loopback):
        raise ValueError(f"{entry} would block the server's own loopback clients")
    if network.prefixlen == network.max_prefixlen:
        return str(network.network_address)
    return f"{network.network_address}/{network.prefixlen}"

def policy(security, plan):
    """Validated product security input (FV-02; FV-06 supplies operator exceptions). Raises ValueError."""
    if not isinstance(security, dict) or set(security) - POLICY_KEYS:
        raise ValueError("unknown security input keys")
    now = security.get("evaluated_at")
    if now is not None and not _int(now, 0, LIMIT_TIME):
        raise ValueError("invalid evaluated_at")
    out = {"per_client": None, "ip_allow": [], "ip_block": [], "accept_differences": [], "exceptions": [], "expired": []}
    limits = security.get("per_client")
    if limits is not None:
        if not isinstance(limits, dict) or not limits or set(limits) - {k for k, _, _ in PER_CLIENT}:
            raise ValueError("invalid per_client limits")
        for key, minimum, maximum in PER_CLIENT:
            if key in limits and not _int(limits[key], minimum, maximum):
                raise ValueError(f"invalid per_client {key}")
        if "softLimit" in limits and "hardLimit" in limits and limits["softLimit"] > limits["hardLimit"]:
            raise ValueError("per_client softLimit exceeds hardLimit")
        out["per_client"] = {key: limits[key] for key, _, _ in PER_CLIENT if key in limits}
    for key, trusted in (("ip_allow", True), ("ip_block", False)):
        entries = security.get(key, [])
        if not isinstance(entries, list) or len(entries) > MAX_LIST:
            raise ValueError(f"invalid {key}")
        for entry in entries:
            value = _network(entry, trusted)
            if value in out[key]:
                raise ValueError(f"{key} lists {value} twice")
            out[key].append(value)
    both = [v for v in out["ip_allow"] if v in out["ip_block"]]
    if both:
        raise ValueError(f"{both[0]} is both allowed and blocked")
    accept = security.get("accept_differences", [])
    if not isinstance(accept, list) or any(code not in WEAKER_CODES for code in accept) or len(set(accept)) != len(accept):
        raise ValueError("invalid accept_differences")
    out["accept_differences"] = sorted(accept)
    exceptions = security.get("exceptions", [])
    if not isinstance(exceptions, list) or len(exceptions) > MAX_LIST:
        raise ValueError("invalid exceptions")
    for item in exceptions:
        if not isinstance(item, dict) or set(item) - EXCEPTION_KEYS or not isinstance(item.get("vhost"), str):
            raise ValueError("invalid exception")
        vhost = item["vhost"]
        if vhost not in plan:
            raise ValueError(f"exception for {vhost}, which is not a cPanel vhost")
        if plan[vhost].get("mode") == "apache":
            raise ValueError(f"exception for {vhost}, which Apache serves (hybrid)")
        reason = item.get("reason")
        if not isinstance(reason, str) or not PRINTABLE.match(reason) or len(reason) > 200:
            raise ValueError(f"exception for {vhost} needs a reason")
        if "approver" in item and (not isinstance(item["approver"], str) or not PRINTABLE.match(item["approver"])
                                   or len(item["approver"]) > 100):
            raise ValueError(f"invalid approver for {vhost}")
        if ("engine" in item) == ("rule_ids" in item):
            raise ValueError(f"exception for {vhost} needs exactly one of engine and rule_ids")
        if "engine" in item and item["engine"] != "off":
            raise ValueError(f"invalid engine for {vhost}")
        ids = item.get("rule_ids", [])
        if not isinstance(ids, list) or ("rule_ids" in item and not 1 <= len(ids) <= 100) \
                or any(not _int(i, 1, 9999999999) for i in ids):
            raise ValueError(f"invalid rule_ids for {vhost}")
        if "expires" in item:
            if not _int(item["expires"], 0, LIMIT_TIME) or now is None:
                raise ValueError(f"exception for {vhost} expires without evaluated_at")
            if item["expires"] <= now:
                out["expired"].append({"vhost": vhost, "reason": reason})
                continue
        out["exceptions"].append({"vhost": vhost, "source": "operator", "engine": item.get("engine"),
                                  "rule_ids": sorted(set(ids)), "reason": reason})
    return out

def vhost_block(engine_off, rule_ids):
    if engine_off:
        return "module mod_security {\n    modsecurity          off\n}\n"
    if rule_ids:
        return ("module mod_security {\n    modsecurity_rules    `SecRuleRemoveById "
                + " ".join(str(i) for i in rule_ids) + "`\n}\n")
    return ""

def server_block(entries):
    return ("module mod_security {\n    ls_enabled           1\n    modsecurity          on\n"
            + "".join(f"    {e['key']:<20} {e['value']}\n" for e in entries) + "}\n")

def _exception_key(entry):
    return (entry["vhost"], entry["source"], entry["engine"] or "", ",".join(str(i) for i in entry["rule_ids"]))

def compile_security(read, plan, userdata, security, vhosts, proxy_vhost, service_name, hybrid_name):
    """The WAF and security part of a compilation. `plan`: cPanel vhost name -> model (with "mode" and
    "service_domains"); `userdata`: cPanel vhost name -> userdata text; `vhosts`: every OLS vhost name of the
    compilation. Returns {"server", "per_client", "ip_allow", "ip_block", "vhosts": {name: block}, "summary"}.
    Raises Blocked (cPanel's ModSecurity cannot be reproduced) or ValueError (invalid security input)."""
    rules = policy(security, plan)
    waf = translate_cpanel(read)
    exceptions = []
    if waf["state"] == "translated":
        checker = waf["checker"]
        for difference in checker.differences:
            difference["accepted"] = difference["weaker"] and difference["code"] in rules["accept_differences"]
        refused = [d for d in checker.differences if d["weaker"] and not d["accepted"]]
        blockers = checker.blockers + [f"{d['where']}: {d['detail']} (code {d['code']} not accepted)" for d in refused]
        if blockers:
            raise Blocked("ModSecurity configuration cannot be reproduced on OLS: " + "; ".join(blockers)[:600])
        proxied = "requests proxied to cpsrvd (cPanel turns the rule engine off for them)"
        for name, v in plan.items():
            if v.get("mode") == "apache":
                for vhost in (name, hybrid_name(name)):
                    exceptions.append({"vhost": vhost, "source": "product", "engine": "off", "rule_ids": [],
                                       "reason": "Apache serves this vhost and applies its own ModSecurity"})
                continue
            if userdata_engine_off(userdata.get(name, ""), name):
                exceptions.append({"vhost": name, "source": "cpanel", "engine": "off", "rule_ids": [],
                                   "reason": "ModSecurity disabled for the domain in cPanel"})
            if v.get("service_domains"):
                exceptions.append({"vhost": service_name(name), "source": "product", "engine": "off", "rule_ids": [],
                                   "reason": proxied})
        exceptions.append({"vhost": proxy_vhost, "source": "product", "engine": "off", "rule_ids": [], "reason": proxied})
        exceptions += rules["exceptions"]
    elif rules["exceptions"]:
        raise ValueError("ModSecurity exceptions without ModSecurity")
    exceptions.sort(key=_exception_key)
    unknown = sorted({e["vhost"] for e in exceptions} - set(vhosts))
    if unknown:
        raise ValueError(f"exception for an OLS vhost the compilation does not have: {unknown[0]}")
    blocks = {}
    for vhost in vhosts:
        mine = [e for e in exceptions if e["vhost"] == vhost]
        block = vhost_block(any(e["engine"] == "off" for e in mine), sorted({i for e in mine for i in e["rule_ids"]}))
        if block:
            blocks[vhost] = block
    per_client = ""
    if rules["per_client"]:
        per_client = "perClientConnLimit {\n" + "".join(f"    {k:<20} {v}\n" for k, v in rules["per_client"].items()) + "}\n"
    if waf["state"] == "absent":
        summary_waf, server = {"state": "absent"}, ""
    else:
        summary_waf = {"state": "translated", "engine": waf["engine"], "audit_log": AUDIT_LOG, "inputs": waf["inputs"],
                       "rule_files": waf["rule_files"], "data_files": waf["checker"].data_files,
                       "rules": len(waf["checker"].rules), "disabled_rules": waf["disabled_rules"],
                       "differences": waf["checker"].differences, "exceptions": exceptions}
        server = server_block(waf["entries"])
    return {"server": server, "per_client": per_client, "ip_allow": rules["ip_allow"], "ip_block": rules["ip_block"],
            "vhosts": blocks, "summary": {"waf": summary_waf,
                                          "security": {"per_client": rules["per_client"], "ip_allow": rules["ip_allow"],
                                                       "ip_block": rules["ip_block"],
                                                       "accept_differences": rules["accept_differences"],
                                                       "expired_exceptions": rules["expired"]}}}

ACCESS_BLOCK = re.compile(r"^accessControl \{\n((?:    [^\n]*\n)*)\}\n", re.M)

def apply_server(config, compiled):
    """Server configuration with the security part: the IP lists merged into the server accessControl (trusted
    clients get OLS's "T" suffix: exempt from per-client limits and bans, never from the WAF; a blocked entry
    leaves the allow list), perClientConnLimit after it, the module block at the end."""
    found = ACCESS_BLOCK.findall(config)
    if len(found) != 1 or "perClientConnLimit" in config or "module mod_security" in config:
        raise ValueError("server template must hold exactly one accessControl block and no security settings")
    values = {"allow": None, "deny": None}
    for line in found[0].split("\n")[:-1]:
        key, _, value = line.strip(" ").partition(" ")
        if key not in values or values[key] is not None:
            raise ValueError("unexpected accessControl line in the server template")
        values[key] = [v for v in value.strip(" ").split(", ") if v]
    allow = [v for v in values["allow"] or [] if v not in compiled["ip_block"]]
    for entry in compiled["ip_allow"]:
        if entry in allow:
            allow[allow.index(entry)] = entry + "T"
        else:
            allow.append(entry + "T")
    deny = (values["deny"] or []) + compiled["ip_block"]
    if not allow:
        raise ValueError("the blocked addresses leave no client allowed")
    block = "accessControl {\n    allow                " + ", ".join(allow) + "\n" + (
        "    deny                 " + ", ".join(deny) + "\n" if deny else "") + "}\n"
    start = ACCESS_BLOCK.search(config)
    return config[:start.start()] + block + compiled["per_client"] + config[start.end():] + compiled["server"]

# Blocked-request log: libmodsecurity 3's native serial audit log (SecAuditLogType Serial). The parser works
# on bytes (any encoding, cut anywhere) and returns printable ASCII only.
BOUNDARY = re.compile(rb"^---([A-Za-z0-9]{8,64})---([A-Z])--\Z")
AUDIT_A = re.compile(rb"^\[([0-9]{2})/([A-Za-z]{3})/([0-9]{4}):([0-9]{2}):([0-9]{2}):([0-9]{2}) ([+-])([0-9]{2})([0-9]{2})\]"
                     rb" [^ ]+ ([0-9A-Fa-f:.]{2,45}) [0-9]+ [^ ]+ [0-9]+\Z")
MESSAGE = re.compile(rb"^ModSecurity: (Access denied with code [0-9]{3}|Warning\.)")
DENIED = b"ModSecurity: Access denied"
MAX_LINE = 16384
MAX_SECTION_LINES = 200
MONTHS = (b"Jan", b"Feb", b"Mar", b"Apr", b"May", b"Jun", b"Jul", b"Aug", b"Sep", b"Oct", b"Nov", b"Dec")

def _clean(value, limit):
    """Printable ASCII only (log-injection protection: every other byte becomes "?"), at most `limit` bytes."""
    return re.sub(rb"[^\x20-\x7e]", b"?", value)[:limit].decode("ascii")

def _field(line, name):
    match = re.search(rb'\[' + name + rb' "((?:[^"\\]|\\.)*)"\]', line)
    return match.group(1).replace(b'\\"', b'"') if match else None

def _days(year, month):
    if month == 2:
        return 29 if year % 4 == 0 and (year % 100 != 0 or year % 400 == 0) else 28
    return 30 if month in (4, 6, 9, 11) else 31

def _time(head):
    """ISO 8601 UTC time of an audit log A line, or None."""
    day, year = int(head.group(1)), int(head.group(3))
    hour, minute, second = int(head.group(4)), int(head.group(5)), int(head.group(6))
    if head.group(2) not in MONTHS or not 1970 <= year <= 9999 or hour > 23 or minute > 59 or second > 59:
        return None
    month = MONTHS.index(head.group(2)) + 1
    if not 1 <= day <= _days(year, month):
        return None
    local = datetime(year, month, day, hour, minute, second, tzinfo=timezone.utc).timestamp()
    offset = (int(head.group(8)) * 3600 + int(head.group(9)) * 60) * (1 if head.group(7) == b"+" else -1)
    return datetime.fromtimestamp(local - offset, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

def _client(value):
    """The client address in canonical form; IPv6 with an embedded IPv4 part is refused (spelled differently
    by different libraries)."""
    if b":" in value and b"." in value:
        return None
    try:
        return str(ipaddress.ip_address(value.decode("ascii")))
    except ValueError:
        return None

def _record(sections):
    head = AUDIT_A.match((sections.get(b"A") or [b""])[0])
    if not head:
        return None
    moment, client = _time(head), _client(head.group(10))
    messages = [line for line in sections.get(b"H", []) if MESSAGE.match(line)]
    if moment is None or client is None or not messages:
        return None
    denied = [line for line in messages if line.startswith(DENIED)]
    chosen = denied[0] if denied else messages[0]
    request = (sections.get(b"B") or [b""])[0].split(b" ")
    uri = request[1] if len(request) >= 3 else _field(chosen, b"uri")
    host = None
    for line in sections.get(b"B", [])[1:]:
        if line[:5].lower() == b"host:":
            host = line[5:].strip(b" \t")
            break
    if host is None:
        host = _field(chosen, b"hostname")
    if host is not None:
        host = re.sub(rb":[0-9]+\Z", b"", host)
        host = host.lower().decode("ascii") if re.match(rb"^[A-Za-z0-9.-]{1,253}\Z", host) else None
    rule_id = _field(chosen, b"id")
    return {"time": moment, "client": client, "vhost": host, "uri": None if uri is None else _clean(uri, 2048),
            "rule_id": int(rule_id) if rule_id is not None and re.match(rb"^[0-9]{1,10}\Z", rule_id) else None,
            "message": _clean(_field(chosen, b"msg") or b"", 512), "action": "deny" if denied else "warning"}

def parse_audit_log(text, limit=200):
    """{"records": [oldest first, at most `limit` of the newest], "skipped": n} from a bounded tail of the audit
    log (str or bytes): a transaction cut at the start, a malformed one or one without rule messages is skipped,
    never guessed. Only the request line's URI and the Host header are taken from the request: no other header
    (cookies, authorization) ever leaves the parser."""
    data = text.encode("utf-8", "surrogateescape") if isinstance(text, str) else text
    limit = max(1, min(limit, 1000))
    records, skipped, current, section = [], 0, None, None
    for raw in data.split(b"\n"):
        line = (raw[:-1] if raw.endswith(b"\r") else raw)[:MAX_LINE]
        boundary = BOUNDARY.match(line)
        if boundary is None:
            if current is not None and section is not None and line != b"":
                lines = current.setdefault(section, [])
                if len(lines) < MAX_SECTION_LINES:
                    lines.append(line)
            continue
        part = boundary.group(2)
        if part == b"A":
            if current is not None:
                skipped += 1
            current, section = {b"id": boundary.group(1)}, b"A"
        elif current is None or current[b"id"] != boundary.group(1):
            if current is not None or part == b"Z":
                skipped += 1
            current, section = None, None
        elif part == b"Z":
            record = _record(current)
            if record is None:
                skipped += 1
            else:
                records.append(record)
                if len(records) > limit:
                    records.pop(0)
            current, section = None, None
        else:
            section = part
    if current is not None:
        skipped += 1
    return {"records": records, "skipped": skipped}
